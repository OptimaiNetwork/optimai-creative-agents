const deferred = () => { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };
test('controller walks idle → downloading(loaded, total) → verifying → ready with real byte progress', async () => {
  const gate = deferred(), seen = [];
  let report;
  const setup = createModelSetupController({ bytes: 4e6, name: 'vision AI', load: ({ onProgress }) => { report = onProgress; return gate.promise; } });
  setup.subscribe(state => seen.push(state.state));
  assert.equal(setup.getState().state, 'idle');
  assert.equal(setup.getState().progress, undefined);
  const done = setup.start();
  assert.equal(setup.getState().state, 'downloading');
  assert.equal(setup.getState().progress, undefined, 'indeterminate until the first byte');
  report({ phase: 'download', progress: 0.25, message: 'Downloading weights.' });
  assert.equal(setup.getState().loaded, 1e6);
  assert.equal(setup.getState().progress, 0.25);
  report({ phase: 'download', progress: 0.42 });
  assert.equal(setup.getState().progress, 0.42, 'a reported fraction is exact, not rounded through bytes');
  report({ phase: 'download', progress: 0.25 });
  assert.equal(setup.getState().progress, 0.42);
  assert.equal(setup.getState().progressLabel, '1.7 MB of 4 MB');
  assert.equal(setup.getState().detail, 'Downloading weights.');
  report({ stage: 'download', loaded: 5e5 });
  assert.equal(setup.getState().loaded, 1.68e6, 'progress never moves backwards within one run');
  report({ stage: 'download', loaded: 3e6, total: 6e6 });
  assert.equal(setup.getState().progress, 0.5, 'a reported total replaces the declared size');
  report({ phase: 'verify', message: 'Checking the checksum.' });
  assert.equal(setup.getState().state, 'verifying');
  assert.equal(setup.getState().progressLabel, '');
  gate.resolve();
  const final = await done;
  assert.equal(final.state, 'ready');
  assert.equal(final.progress, 1);
  assert.match(final.message, /^Vision AI is ready/);
  assert.deepEqual([...new Set(seen)], ['downloading', 'verifying', 'ready']);
  assert.ok(Object.isFrozen(final));
});
