test('abort returns to idle, ignores late progress, and a retry starts a fresh run', async () => {
  const calls = [];
  const setup = createModelSetupController({ bytes: 100, load: ({ signal, onProgress }) => { const call = { signal, onProgress, gate: deferred() }; calls.push(call); return call.gate.promise; } });
  const first = setup.start();
  assert.equal(setup.start(), first, 'a second start joins the running download');
  assert.equal(calls.length, 1);
  calls[0].onProgress({ stage: 'download', loaded: 40 });
  assert.equal(setup.abort().state, 'idle');
  assert.equal(calls[0].signal.aborted, true);
  assert.equal(setup.getState().loaded, 0);
  calls[0].onProgress({ stage: 'download', loaded: 90 });
  calls[0].gate.reject(new DOMException('stopped', 'AbortError'));
  assert.equal((await first).state, 'idle', 'an aborted run never reports failure');
  const retry = setup.start();
  assert.equal(calls.length, 2);
  calls[1].gate.resolve();
  assert.equal((await retry).state, 'ready');
  assert.equal(setup.abort().state, 'ready', 'abort after ready changes nothing');
});
test('failures carry the loader message and code, and retry recovers', async () => {
  let attempt = 0;
  const setup = createModelSetupController({ load: async () => { if (++attempt === 1) throw Object.assign(new Error('Storage is full.'), { code: 'quota' }); } });
  const failed = await setup.start();
  assert.equal(failed.state, 'failed');
  assert.deepEqual(failed.error, { code: 'quota', message: 'Storage is full.' });
  assert.equal((await setup.start()).state, 'ready');
  assert.equal(setup.getState().error, null);
  const plain = createModelSetupController({ name: 'writing AI', load: async () => { throw 'nope'; } });
  assert.match((await plain.start()).message, /^Writing AI could not load/);
  assert.throws(() => createModelSetupController({}), TypeError);
});
test('check applies the policy: ready, unsupported, cached or automatic start, and manual waits', async () => {
  const load = async () => {};
  assert.equal((await createModelSetupController({ load, check: () => ({ ready: true }) }).check()).state, 'ready');
  const unsupported = await createModelSetupController({ load, check: () => ({ available: false, message: 'WebGPU is unavailable.' }) }).check({ autoStart: true });
  assert.deepEqual([unsupported.state, unsupported.message], ['unsupported', 'WebGPU is unavailable.']);
  const blocked = createModelSetupController({ load, policy: getModelSetupPolicy({ requiresWebGPU: true }, { webGPU: false }), check: () => ({ available: true }) });
  assert.equal((await blocked.check()).state, 'unsupported');
  assert.equal((await blocked.start()).state, 'unsupported', 'unsupported never downloads');
  let loads = 0;
  const counting = async () => { loads++; };
  const manual = createModelSetupController({ load: counting, policy: { mode: 'manual', reason: 'Data Saver is on.' }, check: () => ({ available: true }) });
  const waiting = await manual.check({ autoStart: true });
  assert.deepEqual([waiting.state, waiting.automatic, waiting.reason, loads], ['idle', false, 'Data Saver is on.', 0]);
  const cached = await createModelSetupController({ load: counting, policy: { mode: 'manual', reason: '' }, check: () => ({ available: true, cached: true }) }).check({ autoStart: true });
  assert.deepEqual([cached.state, cached.automatic, loads], ['ready', false, 1], 'cached files load even on a manual policy');
  const automatic = createModelSetupController({ load: counting, policy: { mode: 'automatic', reason: '' }, check: () => ({ available: true }) });
  assert.equal((await automatic.check()).automatic, true);
  assert.equal(loads, 1, 'check without autoStart never loads');
  const started = await automatic.check({ autoStart: true });
  assert.deepEqual([started.state, started.automatic, loads], ['ready', true, 2]);
});
test('a user choice during check wins over the late check result', async () => {
  const gate = deferred();
  const setup = createModelSetupController({ load: () => new Promise(() => {}), policy: { mode: 'automatic', reason: '' }, check: () => gate.promise });
  assert.equal(setup.getState().state, 'checking', 'a controller with a check starts in checking, so no Download button flashes');
  const checking = setup.check({ autoStart: true });
  assert.equal(setup.getState().state, 'checking');
  void setup.start();
  gate.resolve({ ready: true });
  assert.equal((await checking).state, 'downloading');
  assert.equal(setup.abort().state, 'idle');
  const failing = deferred(), late = createModelSetupController({ load: async () => {}, check: () => failing.promise });
  const pending = late.check();
  late.abort();
  failing.reject(new Error('late'));
  assert.equal((await pending).state, 'idle');
});
test('an in-flight load elsewhere is observed without a duplicate download, and cancel stops it', async () => {
  let polls = 0, loads = 0, cancelled = 0;
  const status = [{ available: true, loading: true }, { available: true, loading: true }, { available: true, ready: true }];
  const waits = [];
  const setup = createModelSetupController({ load: async () => { loads++; }, pollMs: 250, wait: async ms => { waits.push(ms); }, check: () => status[Math.min(polls++, 2)] });
  const watched = await setup.check({ autoStart: true });
  assert.deepEqual([watched.state, loads, polls, waits], ['ready', 0, 3, [250, 250]]);
  const stuck = createModelSetupController({ load: async () => { loads++; }, cancel: () => cancelled++, pollMs: 5, check: () => ({ available: true, loading: true }) });
  const observing = stuck.check();
  await new Promise(resolve => setTimeout(resolve, 2));
  assert.equal(stuck.getState().state, 'downloading');
  assert.equal(stuck.getState().reason, 'No duplicate download is started.');
  assert.equal((await stuck.check()).state, 'downloading', 'a second check does not start another watcher');
  assert.equal(stuck.abort().state, 'idle');
  assert.equal(cancelled, 1);
  assert.equal((await observing).state, 'idle');
  assert.equal(loads, 0);
});
test('subscribe, reset and dispose', async () => {
  const setup = createModelSetupController({ load: async () => {} });
  let count = 0;
  const off = setup.subscribe(() => count++);
  await setup.start();
  const before = count;
  off();
  assert.equal(setup.reset({ message: 'Reload writing AI to continue.' }).state, 'idle');
  assert.equal(count, before);
  assert.equal(setup.getState().message, 'Reload writing AI to continue.');
  assert.equal(setup.reset({ state: 'unsupported' }).state, 'unsupported');
  assert.equal(setup.reset({ state: 'ready' }).state, 'idle', 'reset cannot claim a model is ready');
  setup.subscribe(() => count++);
  setup.dispose();
  setup.reset();
  assert.equal(count, before);
  let cancelled = 0, reads = 0;
  const observer = createModelSetupController({ load: async () => {}, cancel: () => cancelled++, pollMs: 1, policy: () => { reads++; return { mode: 'manual', reason: 'Read now.' }; }, check: () => ({ available: true, loading: true }) });
  assert.equal(reads, 0, 'a policy function is not read before check');
  const watching = observer.check();
  await new Promise(resolve => setTimeout(resolve, 3));
  observer.dispose();
  assert.equal(cancelled, 0, 'unmounting never cancels a load started elsewhere');
  await watching;
  assert.equal(reads, 1);
  const lazy = createModelSetupController({ load: async () => {}, policy: () => ({ mode: 'manual', reason: 'Data Saver is on.' }), check: () => ({ available: true }) });
  assert.equal((await lazy.check()).reason, 'Data Saver is on.');
});
